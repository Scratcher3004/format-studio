using System.Globalization;
using System.Text;
using System.Text.Json;
using System.Text.Json.Nodes;
using FormatStudio.Dsl;
using FormatStudio.Expressions;
using FormatStudio.Model;
using FormatStudio.Projects;

namespace FormatStudio.Codegen.CSharp;

/// <summary>
/// Generates C# types with <c>Read</c>/<c>Write</c> methods over a <c>ref struct</c> reader and writer, plus the packet
/// id dispatch. Structs become <c>partial struct</c>s (or <c>sealed partial class</c>es when they contain themselves),
/// variants become tagged structs with a <c>Kind</c> field and one field per case, aliases are inlined.
/// </summary>
public sealed class CSharpGenerator : ICodeGenerator
{
    public const string FileMarker = "// <auto-generated by format-studio>";

    public string Name => "csharp";
    public string Marker => FileMarker;

    public GeneratedOutput Generate(FormatProject project, JsonObject options) => new Emitter(project, CSharpOptions.From(options)).Run();
}

internal sealed class CodegenException(string message) : Exception(message);

internal sealed class Emitter(FormatProject project, CSharpOptions options)
{
    private readonly GeneratedOutput _output = new();
    private HashSet<string> _classes = [];
    private int _temp;

    private static readonly HashSet<string> Keywords =
    [
        "abstract", "as", "base", "bool", "break", "byte", "case", "catch", "char", "checked", "class", "const", "continue", "decimal",
        "default", "delegate", "do", "double", "else", "enum", "event", "explicit", "extern", "false", "finally", "fixed", "float", "for",
        "foreach", "goto", "if", "implicit", "in", "int", "interface", "internal", "is", "lock", "long", "namespace", "new", "null",
        "object", "operator", "out", "override", "params", "private", "protected", "public", "readonly", "ref", "return", "sbyte",
        "sealed", "short", "sizeof", "stackalloc", "static", "string", "struct", "switch", "this", "throw", "true", "try", "typeof",
        "uint", "ulong", "unchecked", "unsafe", "ushort", "using", "virtual", "void", "volatile", "while",
    ];

    /// <summary>Member names the generated code itself uses.</summary>
    private static readonly HashSet<string> Reserved = ["Read", "Write", "WriteContent", "Id", "PacketId", "Kind", "Case"];

    public GeneratedOutput Run()
    {
        _classes = FindCycles();
        foreach (var definition in project.Types.Values.OrderBy(d => d.Name, StringComparer.Ordinal))
        {
            if (options.Exclude.Contains(definition.Name) || definition is AliasDef) continue;
            // Temporaries are numbered per file, so that a change to one type doesn't renumber the others.
            _temp = 0;
            try
            {
                var (folder, code) = definition switch
                {
                    StructDef { IsPacket: true } packet => ("Packets", Struct(packet)),
                    StructDef structDef => ("Types", Struct(structDef)),
                    EnumDef enumDef => ("Enums", Enum(enumDef)),
                    VariantDef variant => ("Variants", Variant(variant)),
                    BitfieldDef bitfield => ("Types", Bitfield(bitfield)),
                    _ => throw new CodegenException($"Unsupported definition {definition.Kind}"),
                };
                _output.Files.Add(new GeneratedFile($"{folder}/{definition.Name}.g.cs", code));
            }
            catch (Exception e) when (e is CodegenException or ExprException)
            {
                _output.Diagnostics.Error($"{definition.Name}: {e.Message}", definition.Source);
            }
        }

        if (project.Packets.Any()) _output.Files.Add(new GeneratedFile($"{options.Registry}.g.cs", Registry()));
        return _output;
    }

    // ------------------------------------------------------------------ names and types

    private static string Id(string name) => Keywords.Contains(name) ? "@" + name : name;

    private string Global(string typeName) => $"global::{options.Namespace}.{typeName}";

    /// <summary>The C# member name of a field or case, avoiding the enclosing type name and generated members.</summary>
    private static string Member(string name, string owner) => name == owner || Reserved.Contains(name) ? name + "Value" : Id(name);

    private TypeDef Definition(string name) =>
        project.Find(name) ?? throw new CodegenException($"Unknown type '{name}'");

    private bool IsClass(string name) => _classes.Contains(name);

    private static string PrimitiveType(PrimitiveKind kind) => kind switch
    {
        PrimitiveKind.Bool => "bool",
        PrimitiveKind.U8 => "byte",
        PrimitiveKind.I8 => "sbyte",
        PrimitiveKind.U16 => "ushort",
        PrimitiveKind.I16 => "short",
        PrimitiveKind.U32 or PrimitiveKind.VarUInt32 => "uint",
        PrimitiveKind.I32 or PrimitiveKind.VarInt32 or PrimitiveKind.ZigZag32 => "int",
        PrimitiveKind.U64 or PrimitiveKind.VarUInt64 => "ulong",
        PrimitiveKind.I64 or PrimitiveKind.VarInt64 or PrimitiveKind.ZigZag64 => "long",
        PrimitiveKind.F32 => "float",
        PrimitiveKind.F64 => "double",
        _ => "global::System.Guid",
    };

    /// <summary>The C# type of a value; <paramref name="qualified"/> uses global:: names (for method bodies).</summary>
    private string Type(TypeRef type, bool qualified = false) => type switch
    {
        PrimitiveRef primitive => PrimitiveType(primitive.Kind),
        StringRef => "string",
        BytesRef or NbtRef => "byte[]",
        ArrayRef array => Type(array.Element, qualified) + "[]",
        MapRef map => $"global::System.Collections.Generic.KeyValuePair<{Type(map.Key, qualified)}, {Type(map.Value, qualified)}>[]",
        OptionalRef optional => Nullable(Type(optional.Inner, qualified)),
        SizedRef sized => Type(sized.Inner, qualified),
        FixedPointRef => "double",
        NamedRef named => Definition(named.Name) is AliasDef alias && !options.Exclude.Contains(named.Name)
            ? Type(alias.Target, qualified)
            : qualified ? Global(named.Name) : named.Name,
        _ => throw new CodegenException($"Unsupported type {type}"),
    };

    private static string Nullable(string type) => type.EndsWith('?') ? type : type + "?";

    private bool IsValueType(TypeRef type) => project.Unalias(type) switch
    {
        PrimitiveRef or FixedPointRef => true,
        SizedRef sized => IsValueType(sized.Inner),
        NamedRef named => Definition(named.Name) is EnumDef or BitfieldDef || Definition(named.Name) is StructDef or VariantDef && !IsClass(named.Name),
        _ => false,
    };

    private string Endian(PrimitiveRef primitive) =>
        Primitives.HasEndian(primitive.Kind) ? (primitive.Endian ?? project.Defaults.Endian) == Model.Endian.Big ? "BE" : "LE" : "";

    private string Method(PrimitiveRef primitive) => primitive.Kind switch
    {
        PrimitiveKind.Bool => "Bool",
        PrimitiveKind.U8 => "U8",
        PrimitiveKind.I8 => "I8",
        PrimitiveKind.VarUInt32 => "VarUInt32",
        PrimitiveKind.VarUInt64 => "VarUInt64",
        PrimitiveKind.VarInt32 => "VarInt32",
        PrimitiveKind.VarInt64 => "VarInt64",
        PrimitiveKind.ZigZag32 => "ZigZag32",
        PrimitiveKind.ZigZag64 => "ZigZag64",
        PrimitiveKind.Uuid => "Uuid" + Endian(primitive),
        var kind => kind.ToString().ToUpperInvariant() + Endian(primitive),
    };

    private string Temp(string name) => $"__{name}{_temp++}";

    private static string Literal(string text) => JsonSerializer.Serialize(text);

    private static string Escape(string text) => text.Replace("&", "&amp;").Replace("<", "&lt;").Replace(">", "&gt;");

    private static void Doc(CodeWriter w, string? doc, params string?[] remarks)
    {
        if (doc != null)
        {
            w.Line("/// <summary>");
            foreach (var line in doc.Split('\n')) w.Line(("/// " + Escape(line)).TrimEnd());
            w.Line("/// </summary>");
        }

        var parts = remarks.Where(r => r != null).ToList();
        if (parts.Count > 0) w.Line($"/// <remarks>{Escape(string.Join(" ", parts))}</remarks>");
    }

    private string Header()
    {
        var builder = new StringBuilder();
        builder.Append(CSharpGenerator.FileMarker).Append('\n');
        builder.Append($"// Generated by format-studio from project '{project.Settings.Name}'{(project.Settings.Version != null ? $" ({project.Settings.Version})" : "")}.\n");
        builder.Append("// Do not edit: change the format definitions and regenerate.\n");
        builder.Append("#nullable enable\n");
        builder.Append("#pragma warning disable CS1591, CS0108, CS8618\n\n");
        builder.Append($"using {options.RuntimeNamespace};\n\n");
        builder.Append($"namespace {options.Namespace};\n\n");
        return builder.ToString();
    }

    // ------------------------------------------------------------------ cycles

    /// <summary>Types that contain themselves by value (directly or through other types) must be classes.</summary>
    private HashSet<string> FindCycles()
    {
        var edges = new Dictionary<string, List<string>>(StringComparer.Ordinal);
        foreach (var definition in project.Types.Values)
        {
            var targets = new List<string>();
            switch (definition)
            {
                case StructDef structDef:
                    foreach (var field in structDef.Fields) targets.AddRange(ByValue(field.Type));
                    break;
                case VariantDef variant:
                    foreach (var variantCase in variant.Cases.Where(c => c.Type != null)) targets.AddRange(ByValue(variantCase.Type!));
                    break;
            }

            edges[definition.Name] = targets;
        }

        // Tarjan's strongly connected components.
        var index = 0;
        var indices = new Dictionary<string, int>(StringComparer.Ordinal);
        var lowLinks = new Dictionary<string, int>(StringComparer.Ordinal);
        var stack = new Stack<string>();
        var onStack = new HashSet<string>(StringComparer.Ordinal);
        var result = new HashSet<string>(StringComparer.Ordinal);

        void Connect(string node)
        {
            indices[node] = lowLinks[node] = index++;
            stack.Push(node);
            onStack.Add(node);
            foreach (var next in edges.GetValueOrDefault(node) ?? [])
            {
                if (!edges.ContainsKey(next)) continue;
                if (!indices.ContainsKey(next))
                {
                    Connect(next);
                    lowLinks[node] = Math.Min(lowLinks[node], lowLinks[next]);
                }
                else if (onStack.Contains(next))
                {
                    lowLinks[node] = Math.Min(lowLinks[node], indices[next]);
                }
            }

            if (lowLinks[node] != indices[node]) return;
            var component = new List<string>();
            string member;
            do
            {
                member = stack.Pop();
                onStack.Remove(member);
                component.Add(member);
            } while (member != node);

            if (component.Count > 1 || edges[node].Contains(node)) result.UnionWith(component);
        }

        foreach (var node in edges.Keys.Order(StringComparer.Ordinal))
            if (!indices.ContainsKey(node)) Connect(node);
        return result;
    }

    private IEnumerable<string> ByValue(TypeRef type)
    {
        switch (type)
        {
            case OptionalRef optional:
                return ByValue(optional.Inner);
            case SizedRef sized:
                return ByValue(sized.Inner);
            case NamedRef named when project.Find(named.Name) is AliasDef alias:
                return ByValue(alias.Target).Append(named.Name);
            case NamedRef named:
                return [named.Name];
            default:
                return [];
        }
    }

    // ------------------------------------------------------------------ enums and bitfields

    private string Enum(EnumDef enumDef)
    {
        var w = new CodeWriter();
        Doc(w, enumDef.Doc, enumDef.Title != null ? $"Schema name: {enumDef.Title}." : null, $"Default wire type: {enumDef.Type}.");
        if (enumDef.Flags) w.Line("[global::System.Flags]");
        w.Open($"public enum {enumDef.Name} : {PrimitiveType(enumDef.Type.Kind)}");
        foreach (var member in enumDef.Members)
        {
            Doc(w, member.Doc, member.Title != null ? $"Schema name: {member.Title}." : null);
            w.Line($"{Id(member.Name)} = {member.Value.ToString(CultureInfo.InvariantCulture)},");
        }

        w.Close();
        return Header() + w;
    }

    private string Bitfield(BitfieldDef bitfield)
    {
        var w = new CodeWriter();
        Doc(w, bitfield.Doc, $"Packed into {bitfield.Base}.");
        w.Open($"public partial struct {bitfield.Name} : {options.SerializableInterface}<{bitfield.Name}>");
        foreach (var member in bitfield.Members) w.Line($"public {BitMemberType(member)} {Member(member.Name, bitfield.Name)};");
        w.Line();

        w.Open($"public static {bitfield.Name} Read(ref {options.ReaderType} reader)");
        w.Line($"var raw = (ulong)reader.Read{Method(bitfield.Base)}();");
        w.Line($"var result = new {bitfield.Name}();");
        foreach (var (member, shift) in Simulation.Bitfields.Layout(bitfield))
        {
            var mask = member.Bits >= 64 ? "ulong.MaxValue" : $"0x{(1UL << member.Bits) - 1:X}UL";
            var field = Member(member.Name, bitfield.Name);
            var value = member.Signed
                ? $"(long)(raw << {64 - shift - member.Bits}) >> {64 - member.Bits}"
                : $"(raw >> {shift}) & {mask}";
            w.Line(member.Type switch
            {
                "bool" => $"result.{field} = ((raw >> {shift}) & 1UL) != 0;",
                null => $"result.{field} = ({BitMemberType(member)})({value});",
                var enumName => $"result.{field} = ({Global(enumName)})({value});",
            });
        }

        w.Line("return result;");
        w.Close();
        w.Line();

        w.Open($"public readonly void Write(ref {options.WriterType} writer)");
        w.Line("ulong raw = 0;");
        foreach (var (member, shift) in Simulation.Bitfields.Layout(bitfield))
        {
            var mask = member.Bits >= 64 ? "ulong.MaxValue" : $"0x{(1UL << member.Bits) - 1:X}UL";
            var field = Member(member.Name, bitfield.Name);
            var value = member.Type switch
            {
                "bool" => $"({field} ? 1UL : 0UL)",
                null when member.Signed => $"(ulong)(long){field}",
                null => $"(ulong){field}",
                _ => $"(ulong)(long){field}",
            };
            w.Line($"raw |= ({value} & {mask}) << {shift};");
        }

        w.Line($"writer.Write{Method(bitfield.Base)}(({PrimitiveType(bitfield.Base.Kind)})raw);");
        w.Close();
        w.Close();
        return Header() + w;
    }

    private static string BitMemberType(BitFieldMember member) => member.Type switch
    {
        "bool" => "bool",
        null => (member.Signed, member.Bits) switch
        {
            (true, <= 32) => "int",
            (true, _) => "long",
            (false, <= 32) => "uint",
            _ => "ulong",
        },
        var enumName => enumName,
    };

    // ------------------------------------------------------------------ structs

    private sealed class Context
    {
        public string Reader { get; init; } = "reader";
        public string Writer { get; init; } = "writer";
        public required Func<string, Value?> Resolve { get; init; }
        public FieldDef? Field { get; init; }
    }

    private enum Kind
    {
        Bool,
        Number,
        Float,
        Text,
        Null,
        Other,
    }

    /// <param name="Code">The value converted for arithmetic (long, double or bool).</param>
    /// <param name="Raw">The plain access, for null checks, members and len().</param>
    /// <param name="MayBeNull">Optional or conditional: len() and member access must check for null.</param>
    private sealed record Value(string Code, string Raw, Kind Kind, TypeRef? Type, bool MayBeNull = false);

    /// <param name="conditional">The field has a condition, so its C# type is nullable.</param>
    private Value FieldValue(string access, TypeRef type, bool conditional)
    {
        var resolved = project.Unalias(type);
        var mayBeNull = conditional;
        var nullableValueType = conditional && IsValueType(type);
        if (resolved is OptionalRef optional)
        {
            resolved = project.Unalias(optional.Inner);
            mayBeNull = true;
            nullableValueType = IsValueType(optional.Inner);
        }

        var safe = nullableValueType ? $"({access} ?? default)" : access;
        return resolved switch
        {
            PrimitiveRef { Kind: PrimitiveKind.Bool } => new Value(safe, access, Kind.Bool, type, mayBeNull),
            PrimitiveRef { Kind: PrimitiveKind.F32 or PrimitiveKind.F64 } or FixedPointRef => new Value($"(double){safe}", access, Kind.Float, type, mayBeNull),
            PrimitiveRef { Kind: PrimitiveKind.Uuid } => new Value(access, access, Kind.Other, type, mayBeNull),
            PrimitiveRef => new Value($"(long){safe}", access, Kind.Number, type, mayBeNull),
            NamedRef named when Definition(named.Name) is EnumDef => new Value($"(long){safe}", access, Kind.Number, type, mayBeNull),
            StringRef => new Value(access, access, Kind.Text, type, mayBeNull),
            _ => new Value(access, access, Kind.Other, type, mayBeNull),
        };
    }

    private Value Translate(Expr expression, Context context)
    {
        switch (expression)
        {
            case LiteralExpr { Value: null }:
                return new Value("null", "null", Kind.Null, null);
            case LiteralExpr { Value: bool b }:
                return new Value(b ? "true" : "false", b ? "true" : "false", Kind.Bool, null);
            case LiteralExpr { Value: decimal d }:
                var number = d > long.MaxValue ? $"{d.ToString(CultureInfo.InvariantCulture)}UL" : $"{d.ToString(CultureInfo.InvariantCulture)}L";
                return new Value(number, number, Kind.Number, null);
            case LiteralExpr { Value: double f }:
                var text = f.ToString("R", CultureInfo.InvariantCulture) + "d";
                return new Value(text, text, Kind.Float, null);
            case LiteralExpr { Value: string s }:
                return new Value(Literal(s), Literal(s), Kind.Text, null);
            case NameExpr { Name: "_parent" or "_root" }:
                throw new CodegenException("_parent and _root are not supported by the C# generator");
            case NameExpr name:
                return context.Resolve(name.Name) ?? throw new CodegenException($"Unknown name '{name.Name}' in an expression");
            case EnumConstExpr constant:
                if (Definition(constant.Enum) is not EnumDef enumDef || enumDef.FindByName(constant.Member) == null)
                    throw new CodegenException($"Unknown enum constant {constant}");
                var member = $"{Global(constant.Enum)}.{Id(constant.Member)}";
                return new Value($"(long){member}", member, Kind.Number, new NamedRef(constant.Enum));
            case MemberExpr memberExpr:
            {
                var target = Translate(memberExpr.Target, context);
                if (target.Type == null || project.Unalias(target.Type) is not NamedRef named || Definition(named.Name) is not StructDef structDef)
                    throw new CodegenException($"Can't access '{memberExpr.Name}' in {memberExpr}");
                var field = structDef.Fields.FirstOrDefault(f => f.Name == memberExpr.Name && f.IsInput)
                    ?? throw new CodegenException($"{structDef.Name} has no field '{memberExpr.Name}'");
                return FieldValue($"{target.Raw}.{Member(field.Name, structDef.Name)}", field.Type,
                    field.If != null);
            }
            case IndexExpr indexExpr:
            {
                var target = Translate(indexExpr.Target, context);
                var index = Translate(indexExpr.Index, context);
                if (target.Type == null || project.Unalias(target.Type) is not ArrayRef array)
                    throw new CodegenException($"Can't index {indexExpr.Target}");
                return FieldValue($"{target.Raw}[(int){index.Code}]", array.Element, false);
            }
            case UnaryExpr unary:
            {
                var operand = Translate(unary.Operand, context);
                return unary.Operator switch
                {
                    "!" => new Value($"!{Bool(operand)}", "", Kind.Bool, null),
                    "-" => new Value($"(-{operand.Code})", "", operand.Kind == Kind.Float ? Kind.Float : Kind.Number, null),
                    _ => new Value($"(~{operand.Code})", "", Kind.Number, null),
                };
            }
            case BinaryExpr binary:
                return Binary(binary, context);
            case ConditionalExpr conditional:
            {
                var then = Translate(conditional.Then, context);
                var otherwise = Translate(conditional.Else, context);
                var code = $"({Bool(Translate(conditional.Condition, context))} ? {then.Code} : {otherwise.Code})";
                return new Value(code, code, then.Kind == Kind.Null ? otherwise.Kind : then.Kind, then.Type ?? otherwise.Type);
            }
            case CallExpr call:
            {
                if (call.Arguments.Count != 1) throw new CodegenException($"{call.Function}() takes one argument");
                var argument = Translate(call.Arguments[0], context);
                var code = call.Function switch
                {
                    "len" => argument.MayBeNull ? $"(long)({argument.Raw}?.Length ?? 0)" : $"(long){argument.Raw}.Length",
                    "bytelen" => $"(long)global::System.Text.Encoding.UTF8.GetByteCount({argument.Raw} ?? \"\")",
                    "tagof" => $"(long){argument.Raw}.Kind",
                    _ => throw new CodegenException($"Unknown function {call.Function}()"),
                };
                return new Value(code, code, Kind.Number, null);
            }
            default:
                throw new CodegenException($"Unsupported expression {expression}");
        }
    }

    private Value Binary(BinaryExpr binary, Context context)
    {
        var left = Translate(binary.Left, context);
        var right = Translate(binary.Right, context);
        var op = binary.Operator;
        switch (op)
        {
            case "==" or "!=" when left.Kind == Kind.Null || right.Kind == Kind.Null:
                return new Value($"({left.Raw} {op} {right.Raw})", "", Kind.Bool, null);
            case "==" or "!=" when left.Kind == Kind.Bool && right.Kind == Kind.Bool:
            case "&" or "|" or "^" when left.Kind == Kind.Bool && right.Kind == Kind.Bool:
                return new Value($"({left.Code} {op} {right.Code})", "", Kind.Bool, null);
            case "==" or "!=" when left.Kind == Kind.Text || right.Kind == Kind.Text:
                return new Value($"({left.Raw} {op} {right.Raw})", "", Kind.Bool, null);
            case "&&" or "||":
                return new Value($"({Bool(left)} {op} {Bool(right)})", "", Kind.Bool, null);
            case "==" or "!=" or "<" or "<=" or ">" or ">=":
                return new Value($"({Numeric(left)} {op} {Numeric(right)})", "", Kind.Bool, null);
            case "<<" or ">>":
                return new Value($"({Numeric(left)} {op} (int){Numeric(right)})", "", Kind.Number, null);
            case "+" when left.Kind == Kind.Text || right.Kind == Kind.Text:
                return new Value($"({left.Raw} + {right.Raw})", "", Kind.Text, null);
            default:
                var kind = left.Kind == Kind.Float || right.Kind == Kind.Float ? Kind.Float : Kind.Number;
                if (kind == Kind.Float && op is "&" or "|" or "^") throw new CodegenException($"Operator {op} needs integers");
                var code = $"({Numeric(left)} {op} {Numeric(right)})";
                return new Value(code, code, kind, null);
        }
    }

    private static string Bool(Value value) => value.Kind switch
    {
        Kind.Bool => value.Code,
        Kind.Number or Kind.Float => $"({value.Code} != 0)",
        Kind.Null => "false",
        _ => $"({value.Raw} != null)",
    };

    private static string Numeric(Value value) => value.Kind == Kind.Bool ? $"({value.Code} ? 1L : 0L)" : value.Code;

    private string Expression(string text, Context context, out Kind kind)
    {
        var value = Translate(Expr.Parse(text), context);
        kind = value.Kind;
        return value.Kind == Kind.Bool ? value.Code : Numeric(value);
    }

    private string Condition(string text, Context context) => Bool(Translate(Expr.Parse(text), context));

    private string Struct(StructDef structDef)
    {
        var name = structDef.Name;
        var isClass = IsClass(name);
        var w = new CodeWriter();
        var remarks = new List<string?>
        {
            structDef.Title != null ? $"Schema name: {structDef.Title}." : null,
            structDef.IsPacket ? $"Packet id {structDef.Id}." : null,
            isClass ? "A class because it contains itself." : null,
        };
        Doc(w, structDef.Doc, remarks.ToArray());

        var interfaceName = structDef.IsPacket ? options.PacketInterface : options.SerializableInterface;
        w.Open($"public {(isClass ? "sealed partial class" : "partial struct")} {name} : {interfaceName}<{name}>");
        if (structDef.IsPacket)
        {
            if (structDef.Id == null) throw new CodegenException("A packet needs an id");
            w.Line($"public const uint Id = {structDef.Id};");
            w.Line();
            w.Line("public static uint PacketId => Id;");
            w.Line();
        }

        foreach (var field in structDef.Fields.Where(f => f.IsInput))
        {
            Doc(w, field.Doc, field.Title != null ? $"Schema name: {field.Title}." : null, $"Wire: {Describe(field.Type)}.",
                field.If != null ? $"Only present if {field.If}." : null);
            w.Line($"public {FieldType(field)} {Member(field.Name, name)};");
            w.Line();
        }

        ReadMethod(structDef, w);
        w.Line();
        WriteMethod(structDef, w, isClass);
        w.Close();
        return Header() + w;
    }

    private static string Describe(TypeRef type) => TypeExpressions.TryFormat(type) ?? type.ToString();

    private string FieldType(FieldDef field)
    {
        var type = Type(field.Type);
        return field.If != null ? Nullable(type) : type;
    }

    private void ReadMethod(StructDef structDef, CodeWriter w)
    {
        var name = structDef.Name;
        w.Open($"public static {name} Read(ref {options.ReaderType} reader)");
        w.Line($"var result = new {Global(name)}();");
        var known = new Dictionary<string, FieldDef>(StringComparer.Ordinal);
        foreach (var field in structDef.Fields)
        {
            var context = new Context
            {
                Field = field,
                Resolve = n => known.TryGetValue(n, out var f) ? FieldValue(Access(f, "result.", structDef), f.Type, f.If != null) : null,
            };

            if (!field.IsInput) w.Line($"{FieldType(field)} __{field.Name} = default;");
            if (field.If != null) w.Open($"if ({Condition(field.If, context)})");
            var value = Read(field.Type, w, context);
            w.Line($"{Access(field, "result.", structDef)} = {value};");
            if (field.Const != null)
            {
                var constant = Constant(field);
                w.Line($"if ({Access(field, "result.", structDef)} != {constant}) throw new {options.ExceptionType}(\"{name}.{field.Name} must be {constant.Replace("\"", "\\\"")}\");");
            }

            if (options.ValidateRanges && (field.Min != null || field.Max != null) && project.Unalias(field.Type) is PrimitiveRef { Kind: not PrimitiveKind.Uuid and not PrimitiveKind.Bool })
            {
                var access = Access(field, "result.", structDef);
                var checks = new List<string>();
                if (field.Min is { } min) checks.Add($"{access} < {min.ToString(CultureInfo.InvariantCulture)}");
                if (field.Max is { } max) checks.Add($"{access} > {max.ToString(CultureInfo.InvariantCulture)}");
                w.Line($"if ({string.Join(" || ", checks)}) throw new {options.ExceptionType}(\"{name}.{field.Name} is out of range\");");
            }

            if (field.If != null) w.Close();
            known[field.Name] = field;
        }

        w.Line("return result;");
        w.Close();
    }

    private static string Access(FieldDef field, string prefix, StructDef owner) =>
        field.IsInput ? prefix + Member(field.Name, owner.Name) : $"__{field.Name}";

    private string Constant(FieldDef field)
    {
        var resolved = project.Unalias(field.Type);
        var constant = field.Const!;
        switch (resolved)
        {
            case NamedRef named when Definition(named.Name) is EnumDef enumDef:
                var memberName = constant.GetValueKind() == JsonValueKind.String ? constant.GetValue<string>() : null;
                if (memberName != null && enumDef.FindByName(memberName) != null) return $"{Global(enumDef.Name)}.{Id(memberName)}";
                return $"({Global(enumDef.Name)}){Simulation.JsonValues.Number(constant)}";
            case PrimitiveRef { Kind: PrimitiveKind.Bool }:
                return constant.GetValueKind() == JsonValueKind.True ? "true" : "false";
            case PrimitiveRef { Kind: PrimitiveKind.F32 or PrimitiveKind.F64 } primitive:
                return $"({PrimitiveType(primitive.Kind)}){Simulation.JsonValues.Double(constant)?.ToString("R", CultureInfo.InvariantCulture)}";
            case PrimitiveRef { Kind: not PrimitiveKind.Uuid } primitive:
                return $"({PrimitiveType(primitive.Kind)}){Simulation.JsonValues.Number(constant)?.ToString(CultureInfo.InvariantCulture)}";
            case StringRef:
                return Literal(constant.ToString());
            default:
                throw new CodegenException($"A const of type {Describe(field.Type)} is not supported");
        }
    }

    private void WriteMethod(StructDef structDef, CodeWriter w, bool isClass)
    {
        var name = structDef.Name;
        w.Open($"public {(isClass ? "" : "readonly ")}void Write(ref {options.WriterType} writer)");
        var fields = structDef.Fields.ToDictionary(f => f.Name, StringComparer.Ordinal);
        var computedDone = new HashSet<string>(StringComparer.Ordinal);
        Value? Resolve(string n)
        {
            if (!fields.TryGetValue(n, out var f)) return null;
            if (f.Const != null) return FieldValue($"({Constant(f)})", f.Type, false);
            if (f.Computed != null && !computedDone.Contains(n)) throw new CodegenException($"Computed field '{n}' is used before it is calculated");
            return FieldValue(Access(f, "this.", structDef), f.Type, f.If != null);
        }

        var context = new Context { Resolve = Resolve };

        // Computed fields are calculated first, so that they can describe later fields (e.g. a count before a list).
        foreach (var field in structDef.Fields.Where(f => f.Computed != null))
        {
            var code = Expression(field.Computed!, context, out var kind);
            var type = Type(field.Type);
            var resolved = project.Unalias(field.Type);
            if (resolved is PrimitiveRef { Kind: PrimitiveKind.Bool }) code = kind == Kind.Bool ? code : $"({code} != 0)";
            else if (kind == Kind.Bool) code = $"({type})({code} ? 1 : 0)";
            else code = resolved is NamedRef ? $"({Type(field.Type, true)})({code})" : $"({type})({code})";
            w.Line($"{type} __{field.Name} = {code};");
            computedDone.Add(field.Name);
        }

        foreach (var field in structDef.Fields)
        {
            var fieldContext = new Context { Resolve = Resolve, Field = field };
            if (field.If != null) w.Open($"if ({Condition(field.If, fieldContext)})");
            var value = field.Const != null ? Constant(field) : Access(field, "this.", structDef);
            if (field.If != null && field.Const == null)
            {
                var present = Temp("value");
                w.Line($"var {present} = {value} ?? throw new {options.ExceptionType}(\"{name}.{field.Name} is required when {field.If.Replace("\"", "'")}\");");
                value = present;
            }
            Write(field.Type, value, w, fieldContext);
            if (field.If != null) w.Close();
        }

        w.Close();
    }

    // ------------------------------------------------------------------ reading values

    private int MinSize(TypeRef type) => project.Unalias(type) switch
    {
        PrimitiveRef primitive => Primitives.MinWireSize(primitive.Kind),
        FixedPointRef fixedPoint => Primitives.MinWireSize(fixedPoint.Base.Kind),
        NamedRef { As: { } wire } => Primitives.MinWireSize(wire.Kind),
        NamedRef named when Definition(named.Name) is EnumDef enumDef => Primitives.MinWireSize(enumDef.Type.Kind),
        _ => 0,
    };

    private string ReadCount(LengthSpec length, CodeWriter w, Context context, int minSize, int? max)
    {
        string raw;
        switch (length.Kind)
        {
            case LengthKind.Fixed:
                return length.Fixed.ToString(CultureInfo.InvariantCulture);
            case LengthKind.Default or LengthKind.Prefix:
                raw = $"{context.Reader}.Read{Method(length.Prefix ?? project.Defaults.Length)}()";
                break;
            case LengthKind.Expression:
                raw = Expression(length.Expression!, context, out _);
                break;
            default:
                throw new CodegenException($"Length {length} is not supported here");
        }

        var count = Temp("count");
        w.Line($"var {count} = {context.Reader}.CheckCount({raw}, {minSize}{(max != null ? $", {max}" : "")});");
        return count;
    }

    private string Read(TypeRef type, CodeWriter w, Context context)
    {
        var reader = context.Reader;
        switch (type)
        {
            case PrimitiveRef primitive:
                return $"{reader}.Read{Method(primitive)}()";
            case StringRef str:
                if ((str.Encoding ?? project.Defaults.String) != StringEncoding.Utf8)
                    throw new CodegenException($"String encoding {str.Encoding} is not supported by the C# generator");
                return str.Length.Kind switch
                {
                    LengthKind.Zero => $"{reader}.ReadUtf8Zero()",
                    LengthKind.Eof => $"{reader}.ReadUtf8({reader}.Remaining)",
                    _ => $"{reader}.ReadUtf8({ReadCount(str.Length, w, context, 1, null)})",
                };
            case BytesRef bytes:
                return bytes.Length.Kind == LengthKind.Eof
                    ? $"{reader}.ReadBytes({reader}.Remaining)"
                    : $"{reader}.ReadBytes({ReadCount(bytes.Length, w, context, 1, context.Field?.MaxItems)})";
            case ArrayRef array:
            {
                var elementType = Type(array.Element, true);
                var result = Temp("array");
                var elementContext = new Context { Reader = reader, Writer = context.Writer, Resolve = context.Resolve };
                if (array.Length.Kind == LengthKind.Eof)
                {
                    var list = Temp("list");
                    w.Line($"var {list} = new global::System.Collections.Generic.List<{elementType}>();");
                    w.Open($"while ({reader}.Remaining > 0)");
                    w.Line($"{list}.Add({Read(array.Element, w, elementContext)});");
                    w.Close();
                    w.Line($"var {result} = {list}.ToArray();");
                    return result;
                }

                var count = ReadCount(array.Length, w, context, MinSize(array.Element), context.Field?.MaxItems);
                w.Line($"var {result} = {NewArray(elementType, count)};");
                var index = Temp("i");
                w.Open($"for (var {index} = 0; {index} < {result}.Length; {index}++)");
                w.Line($"{result}[{index}] = {Read(array.Element, w, elementContext)};");
                w.Close();
                return result;
            }
            case MapRef map:
            {
                var entryType = $"global::System.Collections.Generic.KeyValuePair<{Type(map.Key, true)}, {Type(map.Value, true)}>";
                var count = ReadCount(map.Length, w, context, MinSize(map.Key), context.Field?.MaxItems);
                var result = Temp("map");
                w.Line($"var {result} = new {entryType}[{count}];");
                var index = Temp("i");
                var entryContext = new Context { Reader = reader, Writer = context.Writer, Resolve = context.Resolve };
                w.Open($"for (var {index} = 0; {index} < {result}.Length; {index}++)");
                var key = Temp("key");
                w.Line($"var {key} = {Read(map.Key, w, entryContext)};");
                w.Line($"{result}[{index}] = new {entryType}({key}, {Read(map.Value, w, entryContext)});");
                w.Close();
                return result;
            }
            case OptionalRef optional:
            {
                var result = Temp("optional");
                w.Line($"{Nullable(Type(optional.Inner, true))} {result} = null;");
                w.Open($"if ({reader}.ReadBool())");
                w.Line($"{result} = {Read(optional.Inner, w, new Context { Reader = reader, Writer = context.Writer, Resolve = context.Resolve })};");
                w.Close();
                return result;
            }
            case SizedRef sized:
            {
                var count = ReadCount(sized.Length, w, context, 1, null);
                var sub = Temp("reader");
                w.Line($"var {sub} = {reader}.Slice({count});");
                return Read(sized.Inner, w, new Context { Reader = sub, Writer = context.Writer, Resolve = context.Resolve, Field = context.Field });
            }
            case FixedPointRef fixedPoint:
                return $"({reader}.Read{Method(fixedPoint.Base)}() / {Math.Pow(2, fixedPoint.FractionBits).ToString("R", CultureInfo.InvariantCulture)}d)";
            case NbtRef nbt:
                return $"{reader}.ReadNbt{project.Defaults.NbtFlavorOf(nbt)}()";
            case NamedRef named:
                switch (Definition(named.Name))
                {
                    case AliasDef alias when !options.Exclude.Contains(named.Name):
                        return Read(alias.Target, w, context);
                    case EnumDef enumDef:
                        return $"({Global(enumDef.Name)}){reader}.Read{Method(named.As ?? enumDef.Type)}()";
                    case VariantDef variant when named.Tag != null:
                        return $"{Global(named.Name)}.Read(ref {reader}, ({VariantTagType(variant, true)}){Expression(named.Tag, context, out _)})";
                    default:
                        return $"{Global(named.Name)}.Read(ref {reader})";
                }
            default:
                throw new CodegenException($"Unsupported type {type}");
        }
    }

    private static string NewArray(string elementType, string count)
    {
        var suffix = "";
        while (elementType.EndsWith("[]", StringComparison.Ordinal))
        {
            suffix += "[]";
            elementType = elementType[..^2];
        }

        return $"new {elementType}[{count}]{suffix}";
    }

    // ------------------------------------------------------------------ writing values

    private void WriteCount(LengthSpec length, string count, CodeWriter w, Context context, string what)
    {
        switch (length.Kind)
        {
            case LengthKind.Default or LengthKind.Prefix:
                var prefix = length.Prefix ?? project.Defaults.Length;
                w.Line($"{context.Writer}.Write{Method(prefix)}(({PrimitiveType(prefix.Kind)}){count});");
                break;
            case LengthKind.Fixed:
                w.Line($"if ({count} != {length.Fixed}) throw new {options.ExceptionType}(\"{what} must have exactly {length.Fixed} elements\");");
                break;
        }
    }

    private void Write(TypeRef type, string value, CodeWriter w, Context context)
    {
        var writer = context.Writer;
        var what = context.Field?.Name ?? "value";
        switch (type)
        {
            case PrimitiveRef primitive:
                w.Line($"{writer}.Write{Method(primitive)}({value});");
                break;
            case StringRef str:
                if ((str.Encoding ?? project.Defaults.String) != StringEncoding.Utf8)
                    throw new CodegenException($"String encoding {str.Encoding} is not supported by the C# generator");
                if (str.Length.Kind == LengthKind.Zero)
                {
                    w.Line($"{writer}.WriteUtf8Zero({value});");
                    break;
                }

                if (str.Length.Kind is LengthKind.Default or LengthKind.Prefix or LengthKind.Fixed)
                    WriteCount(str.Length, $"{options.WriterType}.Utf8Length({value})", w, context, what);
                w.Line($"{writer}.WriteUtf8({value});");
                break;
            case BytesRef bytes:
                WriteCount(bytes.Length, $"{value}.Length", w, context, what);
                w.Line($"{writer}.WriteBytes({value});");
                break;
            case ArrayRef array:
            {
                var items = Temp("items");
                w.Line($"var {items} = {value};");
                WriteCount(array.Length, $"{items}.Length", w, context, what);
                var item = Temp("item");
                w.Open($"foreach (var {item} in {items})");
                Write(array.Element, item, w, new Context { Reader = context.Reader, Writer = writer, Resolve = context.Resolve });
                w.Close();
                break;
            }
            case MapRef map:
            {
                var entries = Temp("entries");
                w.Line($"var {entries} = {value};");
                WriteCount(map.Length, $"{entries}.Length", w, context, what);
                var entry = Temp("entry");
                var entryContext = new Context { Reader = context.Reader, Writer = writer, Resolve = context.Resolve };
                w.Open($"foreach (var {entry} in {entries})");
                Write(map.Key, $"{entry}.Key", w, entryContext);
                Write(map.Value, $"{entry}.Value", w, entryContext);
                w.Close();
                break;
            }
            case OptionalRef optional:
            {
                var temp = Temp("optional");
                w.Line($"var {temp} = {value};");
                w.Line($"{writer}.WriteBool({temp} != null);");
                w.Open($"if ({temp} != null)");
                Write(optional.Inner, IsValueType(optional.Inner) ? $"{temp}.Value" : temp, w,
                    new Context { Reader = context.Reader, Writer = writer, Resolve = context.Resolve });
                w.Close();
                break;
            }
            case SizedRef sized:
            {
                var buffer = Temp("buffer");
                var sub = Temp("writer");
                w.Line($"var {buffer} = new global::System.Buffers.ArrayBufferWriter<byte>();");
                w.Line($"var {sub} = new {options.WriterType}({buffer});");
                Write(sized.Inner, value, w, new Context { Reader = context.Reader, Writer = sub, Resolve = context.Resolve, Field = context.Field });
                WriteCount(sized.Length, $"{buffer}.WrittenCount", w, context, what);
                w.Line($"{writer}.WriteBytes({buffer}.WrittenSpan);");
                break;
            }
            case FixedPointRef fixedPoint:
                w.Line($"{writer}.Write{Method(fixedPoint.Base)}(({PrimitiveType(fixedPoint.Base.Kind)})global::System.Math.Round({value} * " +
                       $"{Math.Pow(2, fixedPoint.FractionBits).ToString("R", CultureInfo.InvariantCulture)}d));");
                break;
            case NbtRef nbt:
                w.Line($"{writer}.WriteNbt{project.Defaults.NbtFlavorOf(nbt)}({value});");
                break;
            case NamedRef named:
                switch (Definition(named.Name))
                {
                    case AliasDef alias when !options.Exclude.Contains(named.Name):
                        Write(alias.Target, value, w, context);
                        break;
                    case EnumDef enumDef:
                        var wire = named.As ?? enumDef.Type;
                        w.Line($"{writer}.Write{Method(wire)}(({PrimitiveType(wire.Kind)}){value});");
                        break;
                    case VariantDef when named.Tag != null:
                        w.Line($"{value}.WriteContent(ref {writer});");
                        break;
                    default:
                        w.Line($"{value}.Write(ref {writer});");
                        break;
                }

                break;
            default:
                throw new CodegenException($"Unsupported type {type}");
        }
    }

    // ------------------------------------------------------------------ variants

    private string VariantTagType(VariantDef variant, bool qualified) =>
        variant.Tag is NamedRef tag && Definition(tag.Name) is EnumDef
            ? qualified ? Global(tag.Name) : tag.Name
            : qualified ? $"{Global(variant.Name)}.Case" : "Case";

    private string CaseValue(VariantDef variant, VariantCase variantCase)
    {
        if (variant.Tag is NamedRef tag && Definition(tag.Name) is EnumDef enumDef)
        {
            return variantCase.TagMember != null
                ? $"{Global(enumDef.Name)}.{Id(variantCase.TagMember)}"
                : $"({Global(enumDef.Name)}){variantCase.TagValue}";
        }

        return $"{Global(variant.Name)}.Case.{Id(variantCase.Name)}";
    }

    private string Variant(VariantDef variant)
    {
        var name = variant.Name;
        var isClass = IsClass(name);
        var w = new CodeWriter();
        var tagType = VariantTagType(variant, false);
        Doc(w, variant.Doc, variant.Tag != null ? $"Tag: {Describe(variant.Tag)}." : "The tag is stored outside (see the fields using it).",
            isClass ? "A class because it contains itself." : null);
        w.Open($"public {(isClass ? "sealed partial class" : "partial struct")} {name} : {options.SerializableInterface}<{name}>");

        if (tagType == "Case")
        {
            var underlying = variant.Tag is PrimitiveRef primitive ? PrimitiveType(primitive.Kind) : "long";
            w.Open($"public enum Case : {underlying}");
            foreach (var variantCase in variant.Cases) w.Line($"{Id(variantCase.Name)} = {variantCase.TagValue},");
            w.Close();
            w.Line();
        }

        w.Line("/// <summary>The active case.</summary>");
        w.Line($"public {tagType} Kind;");
        w.Line();
        foreach (var variantCase in variant.Cases.Where(c => c.Type != null))
        {
            Doc(w, variantCase.Doc ?? $"The value of case {variantCase.Name}; only meaningful when Kind is {variantCase.Name}.",
                $"Wire: {Describe(variantCase.Type!)}.");
            w.Line($"public {Type(variantCase.Type!)} {Member(variantCase.Name, name)};");
            w.Line();
        }

        foreach (var variantCase in variant.Cases)
        {
            var member = Member(variantCase.Name, name);
            w.Line(variantCase.Type == null
                ? $"public static {name} From{variantCase.Name}() => new() {{ Kind = {CaseValue(variant, variantCase)} }};"
                : $"public static {name} From{variantCase.Name}({Type(variantCase.Type)} value) => new() {{ Kind = {CaseValue(variant, variantCase)}, {member} = value }};");
        }

        w.Line();
        w.Open($"public static {name} Read(ref {options.ReaderType} reader)");
        switch (variant.Tag)
        {
            case NamedRef tag when Definition(tag.Name) is EnumDef enumDef:
                w.Line($"return Read(ref reader, ({Global(enumDef.Name)})reader.Read{Method(tag.As ?? enumDef.Type)}());");
                break;
            case PrimitiveRef primitive:
                w.Line($"return Read(ref reader, ({Global(name)}.Case)reader.Read{Method(primitive)}());");
                break;
            default:
                w.Line($"throw new {options.ExceptionType}(\"{name} needs its tag from the enclosing type\");");
                break;
        }

        w.Close();
        w.Line();

        w.Open($"public static {name} Read(ref {options.ReaderType} reader, {tagType} kind)");
        w.Line($"var result = new {Global(name)} {{ Kind = kind }};");
        w.Open("switch (kind)");
        var readContext = new Context { Resolve = _ => null };
        foreach (var variantCase in variant.Cases)
        {
            w.Line($"case {CaseValue(variant, variantCase)}:");
            w.Indent();
            if (variantCase.Type != null)
                w.Line($"result.{Member(variantCase.Name, name)} = {Read(variantCase.Type, w, readContext)};");
            w.Line("break;");
            w.Outdent();
        }

        w.Line("default:");
        w.Line($"    throw new {options.ExceptionType}($\"Unknown {name} tag {{kind}}\");");
        w.Close();
        w.Line("return result;");
        w.Close();
        w.Line();

        var readOnly = isClass ? "" : "readonly ";
        w.Open($"public {readOnly}void Write(ref {options.WriterType} writer)");
        switch (variant.Tag)
        {
            case NamedRef tag when Definition(tag.Name) is EnumDef enumDef:
                var wire = tag.As ?? enumDef.Type;
                w.Line($"writer.Write{Method(wire)}(({PrimitiveType(wire.Kind)})Kind);");
                break;
            case PrimitiveRef primitive:
                w.Line($"writer.Write{Method(primitive)}(({PrimitiveType(primitive.Kind)})Kind);");
                break;
        }

        w.Line("WriteContent(ref writer);");
        w.Close();
        w.Line();

        w.Open($"public {readOnly}void WriteContent(ref {options.WriterType} writer)");
        w.Open("switch (Kind)");
        var writeContext = new Context { Resolve = _ => null };
        foreach (var variantCase in variant.Cases)
        {
            w.Line($"case {CaseValue(variant, variantCase)}:");
            w.Indent();
            if (variantCase.Type != null) Write(variantCase.Type, Member(variantCase.Name, name), w, writeContext);
            w.Line("break;");
            w.Outdent();
        }

        w.Line("default:");
        w.Line($"    throw new {options.ExceptionType}($\"Unknown {name} tag {{Kind}}\");");
        w.Close();
        w.Close();
        w.Close();
        return Header() + w;
    }

    // ------------------------------------------------------------------ registry

    private string Registry()
    {
        var w = new CodeWriter();
        var packets = project.Packets.Where(p => p.Id != null).OrderBy(p => p.Id).ThenBy(p => p.Name, StringComparer.Ordinal).ToList();
        var duplicates = packets.GroupBy(p => p.Id).Where(g => g.Count() > 1).ToList();
        foreach (var duplicate in duplicates)
            _output.Diagnostics.Warning($"Packets {string.Join(", ", duplicate.Select(p => p.Name))} share id {duplicate.Key}; only the first is dispatched");
        packets = packets.DistinctBy(p => p.Id).ToList();

        w.Line($"/// <summary>Packet id dispatch for the {packets.Count} packets of '{Escape(project.Settings.Name)}'.</summary>");
        w.Open($"public static partial class {options.Registry}");
        w.Line("/// <summary>Reads the packet with the given id and passes it to the visitor. Returns false for unknown ids.</summary>");
        w.Open($"public static bool Dispatch<TVisitor>(uint id, ref {options.ReaderType} reader, ref TVisitor visitor) where TVisitor : {options.VisitorInterface}");
        w.Open("switch (id)");
        foreach (var packet in packets)
        {
            w.Open($"case {packet.Id}:");
            w.Line($"var packet = {Global(packet.Name)}.Read(ref reader);");
            w.Line("visitor.Visit(ref packet);");
            w.Line("return true;");
            w.Close();
        }

        w.Line("default:");
        w.Line("    return false;");
        w.Close();
        w.Close();
        w.Line();

        w.Line("/// <summary>The packet name for an id, or null.</summary>");
        w.Open("public static string? NameOf(uint id) => id switch");
        foreach (var packet in packets) w.Line($"{packet.Id} => \"{packet.Name}\",");
        w.Line("_ => null,");
        w.Close(";");
        w.Line();
        w.Line("/// <summary>All packet ids.</summary>");
        w.Line($"public static global::System.ReadOnlySpan<uint> Ids => [{string.Join(", ", packets.Select(p => p.Id))}];");
        w.Close();
        return Header() + w;
    }
