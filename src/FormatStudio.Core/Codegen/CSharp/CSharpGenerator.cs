using System.Text.Json.Nodes;
using FormatStudio.Projects;

namespace FormatStudio.Codegen.CSharp;

/// <summary>
/// Generates C# types with <c>Read</c>/<c>Write</c> methods, plus the packet id dispatch. Structs become
/// <c>partial struct</c>s (or <c>sealed partial class</c>es when they contain themselves), variants become tagged structs
/// with a <c>Kind</c> field and one field per case, aliases are inlined. The I/O model decides what the generated code
/// reads from and writes to: spans (<c>csharp</c>) or streams (<c>csharp-stream</c>).
/// </summary>
public sealed class CSharpGenerator(CSharpIo io) : ICodeGenerator
{
    public const string FileMarker = "// <auto-generated by format-studio>";

    public CSharpIo Io => io;

    public string Name => io == CSharpIo.Span ? "csharp" : "csharp-stream";

    public string Title => io == CSharpIo.Span ? "C# (spans)" : "C# (streams)";

    public string Language => "csharp";

    public string Description => io == CSharpIo.Span
        ? "Allocation-light C# over ReadOnlySpan<byte> and IBufferWriter<byte> (ref struct reader and writer). Needs FormatStudio.Runtime."
        : "C# over System.IO.Stream: reads from network or file streams without buffering whole messages. Needs FormatStudio.Runtime.";

    public string DefaultOutput => io == CSharpIo.Span ? "generated/csharp" : "generated/csharp-stream";

    public string Marker => FileMarker;

    public IReadOnlyList<CodegenOption> Options { get; } = CSharpOptions.Describe(io);

    public GeneratedOutput Generate(FormatProject project, JsonObject options, IReadOnlySet<string> skipped)
    {
        var parsed = CSharpOptions.From(options, io);
        parsed.Exclude = skipped;
        return new CSharpEmitter(project, parsed).Run();
    }
}
