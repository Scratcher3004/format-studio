using System.Text.Json.Nodes;
using FormatStudio.Projects;

namespace FormatStudio.Codegen.Java;

/// <summary>
/// Generates Java classes with <c>read(FormatReader)</c> / <c>write(FormatWriter)</c> over <c>InputStream</c> and
/// <c>OutputStream</c>, plus the packet id dispatch. Structs and variants become final classes with public fields, enums
/// become Java enums (flags enums and enums with unknown values become constants of the enum's type), aliases are inlined.
/// </summary>
public sealed class JavaGenerator : ICodeGenerator
{
    public const string FileMarker = "// <auto-generated by format-studio>";

    public string Name => "java-stream";

    public string Title => "Java (streams)";

    public string Language => "java";

    public string Description =>
        "Java 8+ classes over java.io.InputStream and OutputStream. The runtime (FormatReader, FormatWriter) is written into the output by default.";

    public string DefaultOutput => "generated/java";

    public string Marker => FileMarker;

    public IReadOnlyList<CodegenOption> Options { get; } = JavaOptions.Describe();

    public GeneratedOutput Generate(FormatProject project, JsonObject options, IReadOnlySet<string> skipped)
    {
        var parsed = JavaOptions.From(options);
        parsed.Exclude = skipped;
        return new JavaEmitter(project, parsed).Run();
    }

    /// <summary>The runtime's sources (file name → text), as written into the output with <c>includeRuntime</c>.</summary>
    public static IReadOnlyDictionary<string, string> RuntimeSources()
    {
        var assembly = typeof(JavaGenerator).Assembly;
        var result = new SortedDictionary<string, string>(StringComparer.Ordinal);
        foreach (var resource in assembly.GetManifestResourceNames().Where(n => n.StartsWith(ResourcePrefix, StringComparison.Ordinal)))
        {
            using var reader = new StreamReader(assembly.GetManifestResourceStream(resource)!);
            result[resource[ResourcePrefix.Length..]] = reader.ReadToEnd().Replace("\r\n", "\n");
        }

        return result;
    }

    private const string ResourcePrefix = "JavaRuntime/";
}
