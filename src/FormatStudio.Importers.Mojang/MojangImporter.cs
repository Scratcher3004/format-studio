using System.Text.RegularExpressions;
using FormatStudio.Dsl;
using FormatStudio.Model;
using FormatStudio.Projects;

namespace FormatStudio.Importers.Mojang;

public sealed class MojangImportSettings
{
    /// <summary>Release zip or directory of Mojang/bedrock-protocol-docs, relative to the project.</summary>
    public string Schema { get; set; } = "";
    /// <summary>Output folder for the imported definitions, relative to the project.</summary>
    public string Output { get; set; } = "imported";
    /// <summary>
    /// Other snapshots (zips or directories) to take enum values from. Releases up to v1.26.51 don't contain
    /// <c>x-enum-binary-value</c>; newer branches do.
    /// </summary>
    public List<string> EnumValuesFrom { get; set; } = [];
    /// <summary>Wire type of the oneOf control value when it isn't a const field of the cases.</summary>
    public PrimitiveRef VariantTag { get; set; } = new(PrimitiveKind.VarUInt32);
    /// <summary>Use a const enum field at ordinal 0 shared by all cases of a oneOf as the variant tag.</summary>
    public bool ConstTags { get; set; } = true;
    /// <summary>Replace non-packet structs with a single field by an alias of the field type.</summary>
    public bool InlineSingleFieldStructs { get; set; } = true;

    public static MojangImportSettings From(JsonObject? settings)
    {
        var result = new MojangImportSettings();
        if (settings == null) return result;
        result.Schema = settings["schema"]?.ToString() ?? "";
        result.Output = settings["output"]?.ToString() ?? result.Output;
        if (settings["enumValuesFrom"] is JsonArray from) result.EnumValuesFrom = from.Select(f => f!.ToString()).ToList();
        if (settings["variantTag"]?.ToString() is { } tag && Primitives.TryParse(tag, out var primitive)) result.VariantTag = primitive;
        if (settings["constTags"] is JsonValue constTags) result.ConstTags = constTags.GetValue<bool>();
        if (settings["inlineSingleFieldStructs"] is JsonValue inline) result.InlineSingleFieldStructs = inline.GetValue<bool>();
        return result;
    }
}

/// <summary>
/// Imports the JSON schema of Mojang/bedrock-protocol-docs into DSL definitions: one file per packet, struct, enum,
/// variant and alias. Packet payloads are inlined into the packets.
/// </summary>
public sealed partial class MojangImporter
{
    public const string HeaderMarker = "# Generated by format-studio import mojang";

    private readonly MojangImportSettings _settings;
    private readonly SchemaSource _source;
    private readonly List<SchemaSource> _valueSources;
    private readonly Dictionary<string, EnumDef> _previousEnums;
    private readonly FileSandbox _sandbox;
    private readonly ImportResult _result = new();

    private readonly Dictionary<string, string> _names = new(StringComparer.Ordinal);
    private readonly HashSet<string> _usedNames = new(StringComparer.Ordinal);
    private readonly HashSet<string> _payloads = new(StringComparer.Ordinal);
    private readonly Dictionary<string, int> _refCounts = new(StringComparer.Ordinal);
    private readonly Dictionary<string, string> _constTagProperty = new(StringComparer.Ordinal);
    private readonly Dictionary<string, string> _variantsBySignature = new(StringComparer.Ordinal);
    private readonly Dictionary<string, string> _inlineEnumsBySignature = new(StringComparer.Ordinal);
    private readonly Dictionary<string, (string Key, string? Property, List<string> RawNames)> _enumSources = new(StringComparer.Ordinal);
    private readonly Dictionary<string, TypeDef> _definitions = new(StringComparer.Ordinal);

    // The document and property being converted, to find inline enum values in other snapshots.
    private string? _currentDoc;
    private string? _currentProperty;

    // Report sections.
    private readonly Dictionary<string, List<string>> _assumptions = new(StringComparer.Ordinal);
    private readonly List<string> _constTagVariants = [];
    private readonly List<string> _indexTagVariants = [];
    private readonly List<string> _nbtFields = [];
    private readonly List<string> _skipped = [];
    private readonly List<string> _arrayHints = [];
    private readonly List<string> _enumValueReport = [];
    private int _defaultArrayLengths;

    private MojangImporter(MojangImportSettings settings, SchemaSource source, List<SchemaSource> valueSources,
        Dictionary<string, EnumDef> previousEnums, FileSandbox sandbox)
    {
        _settings = settings;
        _source = source;
        _valueSources = valueSources;
        _previousEnums = previousEnums;
        _sandbox = sandbox;
    }

    /// <summary>Converts the schema. When <paramref name="write"/> is set the files are written to the output folder.</summary>
    /// <param name="sandbox">Where files may be read and written; every path of the import must be inside it.</param>
    public static ImportResult Run(MojangImportSettings settings, string projectDirectory, bool write, FormatDefaults? defaults = null,
        FileSandbox? sandbox = null)
    {
        sandbox ??= FileSandbox.Unrestricted;
        if (string.IsNullOrEmpty(settings.Schema)) throw new FormatDefinitionException("import.mojang.schema is not set");
        var source = SchemaSource.Load(Path.GetFullPath(settings.Schema, projectDirectory), sandbox);
        var valueSources = settings.EnumValuesFrom.Select(from => SchemaSource.Load(Path.GetFullPath(from, projectDirectory), sandbox)).ToList();
        var output = sandbox.Check(Path.GetFullPath(settings.Output, projectDirectory));
        var importer = new MojangImporter(settings, source, valueSources, LoadPreviousEnums(output, sandbox), sandbox);
        importer.Convert();
        importer.Validate(defaults);
        importer._result.Report = importer.BuildReport();
        if (write) importer.Write(output);
        return importer._result;
    }

    // ------------------------------------------------------------------ names

    [GeneratedRegex("[^A-Za-z0-9]+")]
    private static partial Regex NonAlphanumeric();

    /// <summary>"Died in Raid?" → DiedInRaid, "(anonymous_namespace)__Foo__Bar" → FooBar.</summary>
    public static string Pascal(string text)
    {
        text = text.Replace("(anonymous_namespace)", "").Replace("'", "");
        var builder = new StringBuilder();
        foreach (var part in NonAlphanumeric().Split(text).Where(p => p.Length > 0))
            builder.Append(char.ToUpperInvariant(part[0])).Append(part, 1, part.Length - 1);
        if (builder.Length == 0) return "Unnamed";
        if (char.IsDigit(builder[0])) builder.Insert(0, '_');
        return builder.ToString();
    }

    /// <summary>Keeps enum member names as they are where possible: "SURVIVAL" stays, "minecraft:foo" becomes minecraft_foo.</summary>
    public static string MemberName(string raw)
    {
        var name = NonAlphanumeric().Replace(raw.Replace("'", ""), "_").Trim('_');
        if (name.Length == 0) return "Unnamed";
        return char.IsDigit(name[0]) ? "_" + name : name;
    }

    private string UniqueTypeName(string name)
    {
        var candidate = name;
        for (var i = 2; !_usedNames.Add(candidate); i++) candidate = name + i;
        return candidate;
    }

    private static string Normalize(string text) => NonAlphanumeric().Replace(text, "").ToLowerInvariant();

    private static string? CleanDoc(string? text)
    {
        if (string.IsNullOrWhiteSpace(text)) return null;
        var lines = text.Replace("\r", "").Split('\n').Select(line => line.Trim());
        return string.Join("\n", lines).Trim();
    }

    // ------------------------------------------------------------------ schema helpers

    private static string? Underlying(JsonObject schema) => schema["x-underlying-type"]?.ToString();

    private static string[]? Options(JsonObject schema) =>
        (schema["x-serialization-options"] as JsonArray)?.Select(o => o!.ToString()).ToArray();

    private static bool IsEnumDoc(JsonObject doc) => doc["enum"] is JsonArray && doc["properties"] == null;

    private static bool IsPacketDoc(JsonObject doc) => doc["$metaProperties"]?["[cereal:packet]"] != null;

    private JsonObject? Doc(string key) => _source.Documents.GetValueOrDefault(key);

    private static IEnumerable<(string Name, JsonObject Schema)> OrderedProperties(JsonObject doc)
    {
        if (doc["properties"] is not JsonObject properties) return [];
        return properties
            .Select((pair, index) => (pair.Key, Schema: (JsonObject)pair.Value!, index))
            .OrderBy(p => p.Schema["x-ordinal-index"]?.GetValue<int>() ?? int.MaxValue)
            .ThenBy(p => p.index)
            .Select(p => (p.Key, p.Schema));
    }

    private void CountRefs(JsonNode? node)
    {
        switch (node)
        {
            case JsonObject obj:
                if (obj["$ref"]?.ToString() is { } reference)
                {
                    var key = SchemaSource.RefKey(reference);
                    _refCounts[key] = _refCounts.GetValueOrDefault(key) + 1;
                }

                foreach (var (_, value) in obj) CountRefs(value);
                break;
            case JsonArray array:
                foreach (var item in array) CountRefs(item);
                break;
        }
    }

    // ------------------------------------------------------------------ conversion

    private void Convert()
    {
        var keys = _source.Documents.Keys.Order(StringComparer.Ordinal).ToList();
        foreach (var key in keys)
        {
            var doc = _source.Documents[key];
            CountRefs(doc);
            if (IsPacketDoc(doc) && doc["$ref"]?.ToString() is { } payload) _payloads.Add(SchemaSource.RefKey(payload));
        }

        foreach (var key in keys.Where(k => !_payloads.Contains(k))) _names[key] = UniqueTypeName(Pascal(key));

        // Find const-tagged variants first: their case structs are written without the tag field.
        foreach (var doc in _source.Documents.Values) FindConstTags(doc);

        foreach (var key in keys)
        {
            if (_payloads.Contains(key)) continue;
            var doc = _source.Documents[key];
            var name = _names[key];
            if (IsPacketDoc(doc)) ConvertPacket(key, doc, name);
            else if (IsEnumDoc(doc)) ConvertEnum(key, doc, name);
            else if (doc["properties"] is JsonObject || doc["type"]?.ToString() == "object") ConvertObjectDoc(key, doc, name);
            else if (doc["oneOf"] is JsonArray) ConvertOneOfDoc(key, doc, name);
            else if (doc["$ref"]?.ToString() is { } reference) ConvertRefDoc(key, doc, name, reference);
            else ConvertPrimitiveDoc(key, doc, name);
        }

        ResolveEnumValues();
        if (_settings.InlineSingleFieldStructs) InlineSingleFieldStructs();
    }

    private void Emit(TypeDef definition, string folder)
    {
        _definitions[definition.Name] = definition;
        _result.Folders[definition.Name] = folder;
    }

    private void ConvertPacket(string key, JsonObject doc, string name)
    {
        var id = doc["$metaProperties"]!["[cereal:packet]"]!.GetValue<long>();
        var details = doc["$metaProperties"]!["[cereal:packet_details]"]?.ToString();
        var packet = new StructDef { Name = name, IsPacket = true, Id = id, Title = doc["title"]?.ToString() };
        var payload = Doc(SchemaSource.RefKey(doc["$ref"]!.ToString()));
        packet.Doc = CleanDoc(string.Join("\n\n", new[] { doc["description"]?.ToString(), details, payload?["description"]?.ToString() }
            .Where(t => !string.IsNullOrWhiteSpace(t)).Distinct()));
        if (packet.Title == name) packet.Title = null;
        if (payload != null) AddFields(packet, payload, null, SchemaSource.RefKey(doc["$ref"]!.ToString()));
        Emit(packet, "packets");
    }

    private void ConvertObjectDoc(string key, JsonObject doc, string name)
    {
        if (doc["properties"] == null && doc["additionalProperties"] is JsonObject)
        {
            Emit(new AliasDef { Name = name, Title = Title(doc, name), Doc = CleanDoc(doc["description"]?.ToString()), Target = Map(doc, name, "Value") },
                "aliases");
            return;
        }

        var stripped = _constTagProperty.GetValueOrDefault(key);
        if (stripped != null && OrderedProperties(doc).Count() == 1) return; // Only the tag: the case has no data.

        var structDef = new StructDef { Name = name, Title = Title(doc, name), Doc = CleanDoc(doc["description"]?.ToString()) };
        AddFields(structDef, doc, stripped, key);
        Emit(structDef, "types");
    }

    private static string? Title(JsonObject doc, string name) => doc["title"]?.ToString() is { } title && title != name ? title : null;

    private void AddFields(StructDef structDef, JsonObject doc, string? skipProperty, string? docKey)
    {
        var required = (doc["required"] as JsonArray)?.Select(r => r!.ToString()).ToHashSet(StringComparer.Ordinal) ?? [];
        var fieldNames = new HashSet<string>(StringComparer.Ordinal);
        foreach (var (property, schema) in OrderedProperties(doc))
        {
            if (property == skipProperty) continue;
            var fieldName = Pascal(property);
            for (var i = 2; !fieldNames.Add(fieldName); i++) fieldName = Pascal(property) + i;

            (_currentDoc, _currentProperty) = (docKey, property);
            var type = ConvertType(schema, structDef.Name, fieldName, null);
            (_currentDoc, _currentProperty) = (null, null);
            var defaultValue = schema["default"]?.DeepClone();
            if (!required.Contains(property) && defaultValue == null) type = new OptionalRef(type);

            var field = new FieldDef
            {
                Name = fieldName,
                Title = property != fieldName ? property : null,
                Doc = CleanDoc(schema["description"]?.ToString()),
                Type = type,
                Default = defaultValue,
                Min = Decimal(schema["minimum"]),
                Max = Decimal(schema["maximum"]),
                MinLength = (int?)Decimal(schema["minLength"]),
                MaxLength = (int?)Decimal(schema["maxLength"]),
                Pattern = schema["pattern"]?.ToString(),
            };
            if (type is not ArrayRef { Length.Kind: LengthKind.Fixed })
            {
                field.MinItems = (int?)Decimal(schema["minItems"]);
                field.MaxItems = (int?)Decimal(schema["maxItems"] ?? schema["maxProperties"]);
            }

            if (schema["const"] is { } constValue) field.Const = ConstValue(schema, constValue);
            if (schema["x-runtime-constraint-description"]?.ToString() is { } constraint)
                field.Doc = CleanDoc((field.Doc != null ? field.Doc + "\n\n" : "") + "Runtime constraint: " + constraint);
            structDef.Fields.Add(field);
        }
    }

    /// <summary>Parses a schema number without trailing zeros ("2193.0" becomes 2193).</summary>
    private static decimal? Decimal(JsonNode? node) => node == null
        ? null
        : decimal.Parse(node.ToJsonString(), System.Globalization.NumberStyles.Float, System.Globalization.CultureInfo.InvariantCulture)
          / 1.0000000000000000000000000000m;

    private JsonNode ConstValue(JsonObject schema, JsonNode constValue)
    {
        if (schema["$ref"]?.ToString() is { } reference && Doc(SchemaSource.RefKey(reference)) is { } target && IsEnumDoc(target))
        {
            var raw = MatchEnumMember(target, constValue.ToString());
            if (raw != null) return JsonValue.Create(MemberName(raw));
        }

        return constValue.DeepClone();
    }

    private static string? MatchEnumMember(JsonObject enumDoc, string value) =>
        ((JsonArray)enumDoc["enum"]!).Select(m => m!.ToString()).FirstOrDefault(m => Normalize(m) == Normalize(value));

    private TypeRef ConvertType(JsonObject schema, string owner, string field, string[]? inherited)
    {
        var options = Options(schema) ?? inherited ?? [];
        var underlying = Underlying(schema);
        var path = $"{owner}.{field}";

        if (schema["oneOf"] is JsonArray) return new NamedRef(ConvertVariant(schema, owner, field));

        if (schema["$ref"]?.ToString() is { } reference)
        {
            var key = SchemaSource.RefKey(reference);
            var target = Doc(key);
            if (target == null || !_names.TryGetValue(key, out var targetName))
            {
                _result.Diagnostics.Error($"{path}: unresolved $ref {reference}");
                return new NamedRef(Pascal(key));
            }

            if (IsEnumDoc(target))
            {
                if (options.Contains("Allow unknown enum values")) _enumAllowUnknown.Add(targetName);
                var enumType = Primitive(Underlying(target), [], "integer", null);
                var wire = Primitive(underlying ?? Underlying(target), options, "integer", path);
                return wire == enumType ? new NamedRef(targetName) : new NamedRef(targetName, wire);
            }

            // A compressed reference to a plain integer type: use the compressed primitive.
            if (options.Contains("Compression") && target["type"]?.ToString() is "integer" or "number")
                return Primitive(underlying ?? Underlying(target), options, target["type"]!.ToString(), path);
            return new NamedRef(targetName);
        }

        if (schema["enum"] is JsonArray) return InlineEnum(schema, owner, field, options, path);

        switch (schema["type"]?.ToString())
        {
            case "boolean":
                return new PrimitiveRef(PrimitiveKind.Bool);
            case "integer" or "number":
                return Primitive(underlying, options, schema["type"]!.ToString(), path);
            case "string":
                return new StringRef(null, LengthSpec.Default);
            case "array":
                return Array(schema, owner, field, options, path);
            case "object" when schema["additionalProperties"] is JsonObject:
                return Map(schema, owner, field);
            case "object" when schema["properties"] is JsonObject:
                var inlineName = UniqueTypeName(owner + field);
                var inlineStruct = new StructDef { Name = inlineName, Doc = CleanDoc(schema["description"]?.ToString()) };
                AddFields(inlineStruct, schema, null, null);
                Emit(inlineStruct, "types");
                return new NamedRef(inlineName);
            default:
                _nbtFields.Add($"`{path}`" + (schema["description"] is { } description ? $" ({Shorten(description.ToString())})" : ""));
                return new NbtRef(null);
        }
    }

    private static string Shorten(string text)
    {
        text = text.Replace('\n', ' ').Replace('\t', ' ').Replace('|', '/');
        while (text.Contains("  ")) text = text.Replace("  ", " ");
        return text.Length > 90 ? text[..87].TrimEnd() + "..." : text.Trim();
    }

    private readonly HashSet<string> _enumAllowUnknown = new(StringComparer.Ordinal);
    private void Assume(string assumption, string path)
    {
        if (!_assumptions.TryGetValue(assumption, out var paths)) _assumptions[assumption] = paths = [];
        if (!paths.Contains(path)) paths.Add(path);
    }

    private PrimitiveRef Primitive(string? underlying, string[] options, string jsonType, string? path)
    {
        var compress = options.Contains("Compression");
        var kind = underlying switch
        {
            "boolean" => PrimitiveKind.Bool,
            "float" => PrimitiveKind.F32,
            "double" => PrimitiveKind.F64,
            "int8" => compress ? PrimitiveKind.ZigZag32 : PrimitiveKind.I8,
            "uint8" => compress ? PrimitiveKind.VarUInt32 : PrimitiveKind.U8,
            "int16" => compress ? PrimitiveKind.ZigZag32 : PrimitiveKind.I16,
            "uint16" => compress ? PrimitiveKind.VarUInt32 : PrimitiveKind.U16,
            "int32" => compress ? PrimitiveKind.ZigZag32 : PrimitiveKind.I32,
            "uint32" => compress ? PrimitiveKind.VarUInt32 : PrimitiveKind.U32,
            "int64" => compress ? PrimitiveKind.ZigZag64 : PrimitiveKind.I64,
            "uint64" => compress ? PrimitiveKind.VarUInt64 : PrimitiveKind.U64,
            _ => jsonType == "number" ? PrimitiveKind.F32 : PrimitiveKind.ZigZag32,
        };

        if (path != null)
        {
            if (compress && underlying is "int8" or "uint8" or "int16" or "uint16")
                Assume($"Compressed `{underlying}` is read as `{Primitives.Name(kind)}`", path);
            if (underlying == null)
                Assume($"`{jsonType}` without x-underlying-type is read as `{Primitives.Name(kind)}`", path.TrimEnd('.'));
        }

        var big = options.Contains("Big Endian") && Primitives.HasEndian(kind);
        return new PrimitiveRef(kind, big ? Endian.Big : null);
    }

    private TypeRef Array(JsonObject schema, string owner, string field, string[] options, string path)
    {
        var items = schema["items"] as JsonObject ?? new JsonObject();
        var minItems = Decimal(schema["minItems"]);
        var maxItems = Decimal(schema["maxItems"] ?? schema["maxProperties"]);
        LengthSpec length;
        if (options.Contains("No size compression"))
        {
            length = new LengthSpec(LengthKind.Prefix, new PrimitiveRef(PrimitiveKind.U32));
        }
        else if (minItems != null && minItems == maxItems)
        {
            length = new LengthSpec(LengthKind.Fixed, Fixed: (int)minItems.Value);
        }
        else
        {
            length = LengthSpec.Default;
            _defaultArrayLengths++;
            if (maxItems == 65535) _arrayHints.Add($"`{path}`: max {maxItems} items, the count may be a `u16` instead of `varuint32`");
        }

        if (schema["description"]?.ToString() is { } description && description.Contains("bitset", StringComparison.OrdinalIgnoreCase))
            _arrayHints.Add($"`{path}`: described as a bitset, probably not an array on the wire");

        // Serialization options on the array apply to the items (e.g. compressed enum values).
        var itemOptions = options.Where(o => o != "No size compression").ToArray();
        var element = ConvertType(items, owner, field + "Item", itemOptions.Length > 0 ? itemOptions : null);
        if (element is PrimitiveRef { Kind: PrimitiveKind.U8 }) return new BytesRef(length);
        return new ArrayRef(element, length);
    }

    private MapRef Map(JsonObject schema, string owner, string field)
    {
        var additional = (JsonObject)schema["additionalProperties"]!;
        if (additional["properties"] is JsonObject entry && entry["key"] is JsonObject key && entry["value"] is JsonObject value)
            return new MapRef(ConvertType(key, owner, field + "Key", null), ConvertType(value, owner, field + "Value", null), LengthSpec.Default);
        var keyType = schema["propertyNames"] is JsonObject names ? ConvertType(names, owner, field + "Key", null) : new StringRef(null, LengthSpec.Default);
        return new MapRef(keyType, ConvertType(additional, owner, field + "Value", null), LengthSpec.Default);
    }

    private NamedRef InlineEnum(JsonObject schema, string owner, string field, string[] options, string path)
    {
        var raws = ((JsonArray)schema["enum"]!).Select(m => m!.ToString()).ToList();
        var enumType = Primitive(Underlying(schema), [], "integer", null);
        var signature = enumType + ":" + string.Join(",", raws);
        if (!_inlineEnumsBySignature.TryGetValue(signature, out var name))
        {
            name = UniqueTypeName(owner + field);
            _inlineEnumsBySignature[signature] = name;
            var enumDef = new EnumDef { Name = name, Type = enumType, Doc = CleanDoc(schema["description"]?.ToString()) };
            AddMembers(enumDef, raws, schema["$enumDescription"] as JsonObject);
            _enumSources[name] = (_currentDoc ?? "", _currentProperty, raws);
            Emit(enumDef, "enums");
        }

        if (options.Contains("Allow unknown enum values")) _enumAllowUnknown.Add(name);
        var wire = Primitive(Underlying(schema), options, "integer", path);
        return wire == enumType ? new NamedRef(name) : new NamedRef(name, wire);
    }

    private void ConvertEnum(string key, JsonObject doc, string name)
    {
        var raws = ((JsonArray)doc["enum"]!).Select(m => m!.ToString()).ToList();
        var enumDef = new EnumDef
        {
            Name = name,
            Title = Title(doc, name),
            Doc = CleanDoc(doc["description"]?.ToString()),
            Type = Primitive(Underlying(doc), [], "integer", null),
        };
        AddMembers(enumDef, raws, doc["$enumDescription"] as JsonObject);
        _enumSources[name] = (key, null, raws);
        Emit(enumDef, "enums");
    }

    private static void AddMembers(EnumDef enumDef, List<string> raws, JsonObject? descriptions)
    {
        var used = new HashSet<string>(StringComparer.Ordinal);
        foreach (var raw in raws)
        {
            var memberName = MemberName(raw);
            for (var i = 2; !used.Add(memberName); i++) memberName = MemberName(raw) + i;
            enumDef.Members.Add(new EnumMember
            {
                Name = memberName,
                Title = memberName != raw ? raw : null,
                Doc = CleanDoc(descriptions?[raw]?.ToString()),
            });
        }
    }

    private void ConvertOneOfDoc(string key, JsonObject doc, string name)
    {
        if (doc["x-control-value-type"] == null && _refCounts.GetValueOrDefault(key) == 0)
        {
            _skipped.Add($"`{key}`: uncontrolled oneOf that no other type references");
            return;
        }

        // Rename the variant created for this document to the document's own name.
        var variantName = ConvertVariant(doc, "", name, preferredName: name);
        if (variantName != name)
            Emit(new AliasDef { Name = name, Target = new NamedRef(variantName), Doc = CleanDoc(doc["description"]?.ToString()) }, "aliases");
    }

    private void ConvertRefDoc(string key, JsonObject doc, string name, string reference)
    {
        var targetKey = SchemaSource.RefKey(reference);
        TypeRef target;
        if (targetKey == key || !_names.ContainsKey(targetKey))
        {
            target = new StringRef(null, LengthSpec.Default);
            Assume("A `$ref` to the document itself is read as a string", key);
        }
        else
        {
            target = new NamedRef(_names[targetKey]);
        }

        var docText = CleanDoc(string.Join("\n\n", new[] { doc["description"]?.ToString(), doc["x-runtime-constraint-description"]?.ToString() }
            .Where(t => t != null)));
        Emit(new AliasDef { Name = name, Title = Title(doc, name), Doc = docText, Target = target }, "aliases");
    }

    private void ConvertPrimitiveDoc(string key, JsonObject doc, string name)
    {
        if (doc["type"] == null)
        {
            _skipped.Add($"`{key}`: no type");
            return;
        }

        Emit(new AliasDef
        {
            Name = name,
            Title = Title(doc, name),
            Doc = CleanDoc(doc["description"]?.ToString()),
            Target = ConvertType(doc, name, "", null),
        }, "aliases");
    }

    // ------------------------------------------------------------------ variants

    private sealed record ConstTag(string EnumKey, JsonObject TagSchema, List<(string CaseKey, string Property, string Raw)> Cases);

    private void FindConstTags(JsonNode? node)
    {
        switch (node)
        {
            case JsonObject obj:
                if (_settings.ConstTags && obj["oneOf"] is JsonArray && TryConstTag(obj) is { } constTag)
                    foreach (var (caseKey, property, _) in constTag.Cases) _constTagProperty[caseKey] = property;
                foreach (var (_, value) in obj) FindConstTags(value);
                break;
            case JsonArray array:
                foreach (var item in array) FindConstTags(item);
                break;
        }
    }

    /// <summary>
    /// All cases are references to objects whose first field is a const of the same enum: that field is the tag
    /// (e.g. ResourcePackClientResponse, DataItem).
    /// </summary>
    private ConstTag? TryConstTag(JsonObject schema)
    {
        var cases = (JsonArray)schema["oneOf"]!;
        string? enumKey = null;
        JsonObject? tagSchema = null;
        var result = new List<(string, string, string)>();
        foreach (var item in cases)
        {
            if (item?["$ref"]?.ToString() is not { } reference) return null;
            var caseKey = SchemaSource.RefKey(reference);
            if (Doc(caseKey) is not { } caseDoc) return null;
            var first = OrderedProperties(caseDoc).FirstOrDefault();
            if (first.Schema?["const"] is not { } constValue || first.Schema["$ref"]?.ToString() is not { } constRef) return null;
            var constEnum = SchemaSource.RefKey(constRef);
            if (enumKey != null && enumKey != constEnum) return null;
            if (Doc(constEnum) is not { } enumDoc || !IsEnumDoc(enumDoc)) return null;
            var raw = MatchEnumMember(enumDoc, constValue.ToString());
            if (raw == null) return null;
            enumKey = constEnum;
            tagSchema ??= first.Schema;
            result.Add((caseKey, first.Name, raw));
        }

        return enumKey == null ? null : new ConstTag(enumKey, tagSchema!, result);
    }

    private string ConvertVariant(JsonObject schema, string owner, string field, string? preferredName = null)
    {
        var path = owner.Length > 0 ? $"{owner}.{field}" : field;
        var variant = new VariantDef { Name = "", Doc = CleanDoc(schema["description"]?.ToString()) };
        var caseNames = new HashSet<string>(StringComparer.Ordinal);

        string UniqueCase(string name)
        {
            var candidate = name;
            for (var i = 2; !caseNames.Add(candidate); i++) candidate = name + i;
            return candidate;
        }

        var constTag = _settings.ConstTags ? TryConstTag(schema) : null;
        if (constTag != null)
        {
            var enumName = _names[constTag.EnumKey];
            var enumDoc = Doc(constTag.EnumKey)!;
            var enumType = Primitive(Underlying(enumDoc), [], "integer", null);
            var wire = Primitive(Underlying(constTag.TagSchema) ?? Underlying(enumDoc), Options(constTag.TagSchema) ?? [], "integer", path);
            variant.Tag = wire == enumType ? new NamedRef(enumName) : new NamedRef(enumName, wire);
            foreach (var (caseKey, _, raw) in constTag.Cases)
            {
                var hasData = OrderedProperties(Doc(caseKey)!).Count() > 1;
                variant.Cases.Add(new VariantCase
                {
                    Name = UniqueCase(MemberName(raw)),
                    TagMember = MemberName(raw),
                    Type = hasData ? new NamedRef(_names[caseKey]) : null,
                });
            }

            _constTagVariants.Add($"`{path}`: tag `{variant.Tag}` from the const field of each case");
        }
        else
        {
            variant.Tag = _settings.VariantTag;
            var cases = (JsonArray)schema["oneOf"]!;
            for (var i = 0; i < cases.Count; i++)
            {
                var caseSchema = (JsonObject)cases[i]!;
                string caseName;
                TypeRef? caseType;
                if (caseSchema["$ref"]?.ToString() is { } reference && _names.TryGetValue(SchemaSource.RefKey(reference), out var refName))
                {
                    caseName = refName;
                    caseType = new NamedRef(refName);
                }
                else if (caseSchema["type"]?.ToString() == "null")
                {
                    caseName = "None";
                    caseType = null;
                }
                else
                {
                    caseName = Pascal(caseSchema["type"]?.ToString() ?? "Value");
                    caseType = ConvertType(caseSchema, owner, field + caseName, null);
                }

                variant.Cases.Add(new VariantCase { Name = UniqueCase(caseName), TagValue = i, Type = caseType });
            }

            _indexTagVariants.Add($"`{path}`: {cases.Count} cases, tag `{variant.Tag}` = case index");
        }

        var signature = DslWriter.Write(variant);
        if (preferredName == null && _variantsBySignature.TryGetValue(signature, out var existing)) return existing;
        variant.Name = preferredName ?? UniqueTypeName(owner + field);
        _variantsBySignature.TryAdd(signature, variant.Name);
        Emit(variant, "variants");
        return variant.Name;
    }

    // ------------------------------------------------------------------ enum values

    private static Dictionary<string, EnumDef> LoadPreviousEnums(string output, FileSandbox sandbox)
    {
        var result = new Dictionary<string, EnumDef>(StringComparer.Ordinal);
        var folder = Path.Combine(output, "enums");
        if (!Directory.Exists(folder)) return result;
        foreach (var file in sandbox.EnumerateFiles(folder, "*.yaml"))
        {
            if (DslReader.Read(File.ReadAllText(file), file, []) is EnumDef enumDef && enumDef.Doc?.Contains(IndexMarker) != true)
                result[enumDef.Name] = enumDef;
        }

        return result;
    }

    private const string IndexMarker = "Values are member indices";

    private void ResolveEnumValues()
    {
        var bySource = new Dictionary<string, int>(StringComparer.Ordinal);
        foreach (var (name, (key, property, raws)) in _enumSources.OrderBy(p => p.Key, StringComparer.Ordinal))
        {
            var enumDef = (EnumDef)_definitions[name];
            enumDef.AllowUnknown = _enumAllowUnknown.Contains(name);
            var sources = new List<string>();
            var releaseValues = EnumSchema(_source, key, property)?["x-enum-binary-value"] as JsonArray;
            for (var i = 0; i < raws.Count; i++)
            {
                var member = enumDef.Members[i];
                if (releaseValues != null && releaseValues.Count == raws.Count)
                {
                    member.Value = releaseValues[i]!.GetValue<long>();
                    sources.Add("release");
                }
                else if (FindInSnapshots(key, property, raws[i]) is { } snapshot)
                {
                    member.Value = snapshot.Value;
                    sources.Add(snapshot.Source);
                }
                else if (_previousEnums.GetValueOrDefault(name)?.FindByName(member.Name) is { } previous)
                {
                    member.Value = previous.Value;
                    sources.Add("previous import");
                }
                else
                {
                    member.Value = i;
                    sources.Add("index");
                }
            }

            var summary = string.Join(" + ", sources.Distinct());
            bySource[summary] = bySource.GetValueOrDefault(summary) + 1;
            if (sources.Contains("index"))
            {
                var indexed = sources.Count(s => s == "index");
                _enumValueReport.Add($"`{name}`: {indexed} of {raws.Count} values are member indices");
                enumDef.Doc = (enumDef.Doc != null ? enumDef.Doc + "\n\n" : "") + IndexMarker + " (not in the schema); verify them.";
            }
        }

        foreach (var (summary, count) in bySource.OrderByDescending(p => p.Value))
            _enumValueReport.Insert(0, $"{count} enums: values from {summary}");
    }

    /// <summary>The enum schema: a document, or a property of a document for inline enums.</summary>
    private static JsonObject? EnumSchema(SchemaSource source, string key, string? property)
    {
        var doc = source.Documents.GetValueOrDefault(key);
        return property == null ? doc : doc?["properties"]?[property] as JsonObject;
    }

    private (long Value, string Source)? FindInSnapshots(string key, string? property, string raw)
    {
        if (key.Length == 0) return null;
        foreach (var snapshot in _valueSources)
        {
            if (EnumSchema(snapshot, key, property) is not { } doc || doc["enum"] is not JsonArray names
                || doc["x-enum-binary-value"] is not JsonArray values || values.Count != names.Count) continue;
            for (var i = 0; i < names.Count; i++)
            {
                if (names[i]!.ToString() == raw)
                    return (values[i]!.GetValue<long>(), $"snapshot {snapshot.MinecraftVersion ?? Path.GetFileName(snapshot.Origin)}");
            }
        }

        return null;
    }

    // ------------------------------------------------------------------ post-processing

    private void InlineSingleFieldStructs()
    {
        foreach (var structDef in _definitions.Values.OfType<StructDef>().Where(s => !s.IsPacket).ToList())
        {
            if (structDef.Fields is not [{ If: null, Const: null, Computed: null } field] || field.Type is OptionalRef) continue;
            var doc = string.Join("\n\n", new[] { structDef.Doc, field.Doc }.Where(d => d != null));
            Emit(new AliasDef
            {
                Name = structDef.Name,
                Title = structDef.Title,
                Doc = $"Single field `{field.Title ?? field.Name}`." + (doc.Length > 0 ? "\n\n" + doc : ""),
                Target = field.Type,
            }, "aliases");
        }
    }

    private void Validate(FormatDefaults? defaults)
    {
        // Without a project, check with the defaults of the Bedrock network protocol (untyped properties are NBT).
        defaults ??= new FormatDefaults { Nbt = NbtFlavor.BedrockNetwork };
        var project = FormatProject.InMemory(_definitions.Values, new ProjectSettings { Defaults = defaults });
        Validation.Validator.Validate(project);
        _result.Diagnostics.AddRange(project.Diagnostics.Where(d => d.Severity != Severity.Info));
        _result.Definitions.AddRange(_definitions.Values.OrderBy(d => d.Name, StringComparer.Ordinal));
    }

    // ------------------------------------------------------------------ output

    private string Header() =>
        $"{HeaderMarker} from Mojang/bedrock-protocol-docs {_source.MinecraftVersion} (protocol {_source.ProtocolVersion}).\n" +
        "# Don't edit: put changes into an override file, see import-report.md.\n";

    private void Write(string output)
    {
        var header = Header();
        var written = new HashSet<string>(StringComparer.Ordinal);
        foreach (var definition in _result.Definitions)
        {
            var file = _sandbox.Check(Path.Combine(output, _result.Folders[definition.Name], definition.Name + ".yaml"));
            written.Add(Path.GetFullPath(file));
            var content = header + DslWriter.Write(definition);
            if (File.Exists(file) && File.ReadAllText(file) == content)
            {
                _result.Unchanged++;
                continue;
            }

            Directory.CreateDirectory(Path.GetDirectoryName(file)!);
            File.WriteAllText(file, content);
            _result.Written.Add(file);
        }

        // Remove files of an earlier import that are gone now. Only files with the generated header are touched.
        if (Directory.Exists(output))
        {
            foreach (var file in _sandbox.EnumerateFiles(output, "*.yaml", recursive: true).ToList())
            {
                if (written.Contains(Path.GetFullPath(file))) continue;
                using (var reader = new StreamReader(file))
                {
                    if (reader.ReadLine()?.StartsWith(HeaderMarker, StringComparison.Ordinal) != true) continue;
                }

                File.Delete(file);
                _result.Deleted.Add(file);
            }
        }

        _result.ReportFile = _sandbox.Check(Path.Combine(output, "import-report.md"));
        File.WriteAllText(_result.ReportFile, _result.Report);
    }

    private string BuildReport()
    {
        var builder = new StringBuilder();
        var definitions = _result.Definitions;
        builder.AppendLine("# Mojang schema import report").AppendLine();
        builder.AppendLine($"Source: `{Path.GetFileName(_source.Origin)}`, Minecraft {_source.MinecraftVersion}, protocol {_source.ProtocolVersion}, " +
                           $"{_source.Documents.Count} schema files.").AppendLine();
        builder.AppendLine("| Kind | Count |").AppendLine("|---|---|");
        builder.AppendLine($"| packets | {definitions.Count(d => d is StructDef { IsPacket: true })} |");
        builder.AppendLine($"| structs | {definitions.Count(d => d is StructDef { IsPacket: false })} |");
        builder.AppendLine($"| enums | {definitions.Count(d => d is EnumDef)} |");
        builder.AppendLine($"| variants | {definitions.Count(d => d is VariantDef)} |");
        builder.AppendLine($"| aliases | {definitions.Count(d => d is AliasDef)} |").AppendLine();
        builder.AppendLine("Imported files are regenerated on every import. Corrections go into files in an override folder that comes " +
                           "after the import folder in the project's `sources`; a definition there replaces the imported one with the same name.")
            .AppendLine();

        Section("Enum values", "The release schema has no numeric enum values; they come from these sources:", _enumValueReport);
        Section("Variants with a const tag", "The tag is the const enum field at ordinal 0 of every case (it is read once, as the tag):",
            _constTagVariants);
        Section("Variants with an index tag", "The control value is assumed to be the case index:", _indexTagVariants);
        Section("Assumptions to verify", null, _assumptions
            .Select(pair => $"{pair.Key}: {pair.Value.Count} × ({string.Join(", ", pair.Value.Take(4).Select(v => $"`{v}`"))}" +
                            $"{(pair.Value.Count > 4 ? ", ..." : "")})")
            .ToList());
        Section("Arrays", $"{_defaultArrayLengths} arrays without serialization options use the default `varuint32` count. Hints:", _arrayHints);
        Section("Untyped properties read as NBT", "Properties without a type are assumed to be network NBT compound tags:", _nbtFields);
        Section("Skipped", null, _skipped);
        Section("Validation", null, _result.Diagnostics.Select(d => d.ToString()).ToList());
        return builder.ToString();

        void Section(string title, string? intro, List<string> lines)
        {
            if (lines.Count == 0) return;
            builder.AppendLine($"## {title}").AppendLine();
            if (intro != null) builder.AppendLine(intro).AppendLine();
            foreach (var line in lines) builder.AppendLine($"- {line}");
            builder.AppendLine();
        }
    }
